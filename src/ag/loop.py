def start(
    root: Path,
    *,
    portrait: str = "",
    anchors: list[dict[str, Any]] | None = None,
    guards: list[str] | None = None,
    defaults: list[str] | None = None,
    fixed: list[str] | None = None,
    continuation_of: str = "",
    contribution: str = "",
) -> dict[str, Any]:
    """Open a worktree. Tracked canonical files stay frozen until finish or abandon.

    Windows freeze is a recoverable ACL deny-write entry. Elsewhere it is the
    user-write bit. Either mechanism is friction, not an absolute security boundary.
    """
    ensure_local_excludes(root)
    from .upgrade import ensure_upgraded

    ensure_upgraded(root)
    state = status(root)
    root = Path(state["root"])
    key = str(state["key"])
    if state["canonical_dirty"]:
        dirty_list = ", ".join(_dirty_files(root))
        dirty_hint = f" ({dirty_list})" if dirty_list else ""
        usage_note(root, "ship", 8, "block", "start canonical dirty")
        raise ChainBroken(
            f"canonical checkout is dirty; not a work site{dirty_hint} "
            "[原因] 主仓存在未提交或未忽略的改动 "
            "[下一步] 请先 git commit / git stash 清理主仓改动后再调用 ag_start"
        )
    if not state["hook_ok"]:
        usage_note(root, "ship", 8, "block", "start hook missing")
        raise ChainBroken(
            "hook is not installed; re-enroll "
            "[原因] Git 门禁钩子未安装或已失效 "
            "[下一步] 请重新调用 ag_enroll 修复钩子后再调用 ag_start"
        )
    from .anchor_map import attention_anchors, hard_rules, resolve_fixed
    from .ticket_doc import (
        collect_redlines,
        flow_target_warnings,
        dropped_redlines,
        merge_anchors,
        previous_redlines,
        require_ticket,
        seal,
        split_document,
        ticket_path,
        write_scene,
    )

    existing = load_task(key)
    if existing and Path(str(existing.get("worktree") or "")).is_dir():
        if existing.get("intent_map_confirmed"):
            from .authorization import validate_ticket

            validate_ticket(root, existing)
            if (fixed is not None and list(fixed) != list(existing.get("fixed") or [])) or (portrait and portrait != existing.get("portrait")):
                raise ChainBroken("await-user-decision: confirmed result changed; preserve the existing goal")
            return status(root)
        existing_wt = Path(str(existing.get("worktree") or ""))
        if not bool(existing.get("intent_map_confirmed")) and ticket_path(root).is_file():
            document = require_ticket(root)
            intent_body, redline_body = split_document(document)
            chosen = str(portrait or existing.get("portrait") or "")
            caller_anchors = None if anchors is None else [dict(item) for item in anchors if isinstance(item, dict)]
            doc_anchors = parse_anchors(intent_body)
            base_anchors = (
                doc_anchors
                if doc_anchors
                else [dict(item) for item in (existing.get("anchors") or []) if isinstance(item, dict)]
            )
            task_anchors = merge_anchors(base_anchors, caller_anchors)
            task_fixed = resolve_fixed(chosen, fixed if fixed is not None else existing.get("fixed"))
            task_rules = hard_rules(task_anchors)
            if not task_fixed and not task_anchors:
                usage_note(root, "ship", 8, "block", "start without intent anchors")
                raise ChainBroken(
                    "intent sync required: provide a locked result or at least one attention anchor "
                    "[原因] <AG_HOME>/projects/<key>/ticket.md 中缺少 anchor: 意图锚点 "
                    "[下一步] 请在 <AG_HOME>/projects/<key>/ticket.md 的 ## 意图 下补充至少一条正反行为闭环 anchor: 后重试"
                )
            redlines = collect_redlines(redline_body, task_anchors, root)
            baseline_prev = list(
                dict.fromkeys(
                    list(existing.get("redlines") or [])
                    + list(existing.get("dropped_redlines") or [])
                    + previous_redlines(root)
                )
            )
            dropped = dropped_redlines(baseline_prev, redlines)
            route = attention_anchors(task_anchors)
            current_id = str(route[0].get("id") or "") if route else ""
            task_id = str(existing.get("id") or "")
            existing["portrait"] = chosen
            existing["anchors"] = task_anchors
            existing["current_anchor"] = current_id
            existing["fixed"] = task_fixed
            existing["fixed_rules"] = task_rules
            if guards is not None:
                existing["guards"] = [str(item).strip() for item in guards if str(item).strip()]
            if defaults is not None:
                existing["defaults"] = [str(item).strip() for item in defaults if str(item).strip()]
            existing["redlines"] = redlines
            existing["dropped_redlines"] = dropped
            flow_warnings = flow_target_warnings(intent_body)
            if flow_warnings:
                existing["prescreen_warnings"] = list(dict.fromkeys(list(existing.get("prescreen_warnings") or []) + flow_warnings))
            preview = seal(
                root,
                intent_body=intent_body,
                redlines=redlines,
                task=existing,
                process="active",
                product="pending",
            )
            ticket_review = _run_ticket_review(
                root,
                intent_body=intent_body,
                portrait=chosen,
                anchors=task_anchors,
                redlines=redlines,
                task_id=task_id,
                goal_link=existing.get("goal_link"),
            )
            existing["ticket_review"] = ticket_review
            preview = write_scene(root, existing, process="active", product="pending") or preview
            doc_path = str(ticket_path(root).resolve())
            existing["anchor_map_path"] = doc_path
            existing["anchor_preview_path"] = doc_path
            existing["anchor_preview"] = preview
            from .authorization import bind_ticket
            from .delivery import task_facts

            bind_ticket(root, existing)
            save_task(key, existing)
            append_task_step(
                root,
                task_id,
                "re-seal",
                ticket_review_outcome=str(ticket_review.get("outcome") or ""),
                report_id=str(ticket_review.get("report_id") or ""),
                task=task_facts(existing),
            )
        try:
            freeze_canonical(root)
            freeze_worktree(existing_wt)
        except Exception:
            thaw_worktree(existing_wt)
            thaw_canonical(root)
            raise
        return status(root)
    if existing:
        raise ChainBroken("worktree-missing: task and goal retained; recover the worktree or abandon before starting another ticket")
    if not _is_canonical(root):
        raise ChainBroken(
            "start from the canonical checkout "
            "[原因] 当前路径不是主仓根目录 "
            "[下一步] 请传入主仓根目录 <PROJECT_ROOT> 调用 ag_start"
        )
    branch = git(root, "rev-parse", "--abbrev-ref", "HEAD")
    if branch in {"HEAD", ""}:
        raise ChainBroken(
            "canonical HEAD is detached "
            "[原因] 主仓处于游离 HEAD 状态 "
            "[下一步] 请先切换回具名分支（如 git switch main/master）后再调用 ag_start"
        )
    chosen = str(portrait or "")
    goal_link = None
    if continuation_of:
        from .delivery import build_delivery_snapshot

        previous = build_delivery_snapshot(root, continuation_of)
        if not previous.get("found") or previous.get("active") or not previous.get("goal", {}).get("confirmed"):
            raise ChainBroken("invalid-continuation: expected a closed, confirmed predecessor")
        parent_link = previous.get("goal_link") or {}
        goal_link = {"task_id": continuation_of, "common_goal": parent_link.get("common_goal") or previous["goal"], "contribution": contribution or chosen, "remaining": previous["remaining"]}
    document = require_ticket(root)
    intent_body, redline_body = split_document(document)
    caller_anchors = None if anchors is None else [dict(item) for item in anchors if isinstance(item, dict)]
    task_anchors = merge_anchors(parse_anchors(intent_body), caller_anchors)
    task_fixed = resolve_fixed(chosen, fixed)
    task_rules = hard_rules(task_anchors)
    if not task_fixed and not task_anchors:
        usage_note(root, "ship", 8, "block", "start without intent anchors")
        raise ChainBroken(
            "intent sync required: provide a locked result or at least one attention anchor "
            "[原因] <AG_HOME>/projects/<key>/ticket.md 中缺少 anchor: 意图锚点 "
            "[下一步] 请在 <AG_HOME>/projects/<key>/ticket.md 的 ## 意图 下补充至少一条正反行为闭环 anchor: 后重试"
        )
    redlines = collect_redlines(redline_body, task_anchors, root)
    prev_redlines = previous_redlines(root)
    dropped = dropped_redlines(prev_redlines, redlines)
    task_guards = [str(item).strip() for item in (guards or []) if str(item).strip()]
    task_defaults = [str(item).strip() for item in (defaults or []) if str(item).strip()]
    route = attention_anchors(task_anchors)
    current_id = str(route[0].get("id") or "") if route else ""
    task_id = uuid.uuid4().hex[:8]
    worktree = ag_home() / "worktrees" / key / task_id
    worktree.parent.mkdir(parents=True, exist_ok=True)
    git(root, "worktree", "add", "-b", f"ag/{task_id}", str(worktree), "HEAD")
    draft = {
        "id": task_id,
        "branch": branch,
        "worktree": str(worktree),
    }
    try:
        flow_warnings = flow_target_warnings(intent_body)
        if flow_warnings:
            draft["prescreen_warnings"] = list(dict.fromkeys(list(draft.get("prescreen_warnings") or []) + flow_warnings))
        preview = seal(
            root,
            intent_body=intent_body,
            redlines=redlines,
            task=draft,
            process="active",
            product="pending",
        )
    except Exception:
        git(root, "worktree", "remove", "--force", str(worktree), check=False)
        raise
    ticket_review = _run_ticket_review(
        root,
        intent_body=intent_body,
        portrait=chosen,
        anchors=task_anchors,
        redlines=redlines,
        task_id=task_id,
        goal_link=goal_link,
    )
    doc_path = str(ticket_path(root).resolve())
    task_blob: dict[str, Any] = {
        "id": task_id,
        "branch": branch,
        "source_head": git(root, "rev-parse", "HEAD"),
        "worktree": str(worktree),
        "portrait": chosen,
        "anchors": task_anchors,
        "anchor_map_path": doc_path,
        "anchor_preview_path": doc_path,
        "anchor_preview": preview,
        "intent_map_confirmed": False,
        "current_anchor": current_id,
        "fixed": task_fixed,
        "fixed_rules": task_rules,
        "guards": task_guards,
        "defaults": task_defaults,
        "redlines": redlines,
        "dropped_redlines": dropped,
        "ticket_review": ticket_review,
        "verified_tree": "",
        "verify": None,
        "goal_link": goal_link,
    }
    preview = write_scene(root, task_blob, process="active", product="pending") or preview
    task_blob["anchor_preview"] = preview
    from .authorization import bind_ticket
    from .delivery import build_delivery_snapshot, task_facts

    bind_ticket(root, task_blob)
    save_task(key, task_blob)
    try:
        freeze_canonical(root)
        freeze_worktree(worktree)
    except Exception:
        thaw_worktree(worktree)
        thaw_canonical(root)
        raise
    usage_note(root, "ship", 2, "help", "opened")
    line = (chosen.strip().splitlines() or [""])[0][:80]
    append_task_step(root, task_id, "start", portrait_line=line, worktree=str(worktree), task=task_facts(task_blob))
    state = status(root)
    append_task_step(root, task_id, "anchor-preview", anchor_map_path=str(state.get("anchor_map_path") or ""), audit_anchor_map_path=str((state.get("task") or {}).get("audit_anchor_map_path") or ""), anchor_preview=str(state.get("anchor_preview") or ""), audit_anchor_preview_path=str((state.get("task") or {}).get("audit_anchor_preview_path") or ""))
    return state


def _refuse_dirty_verify(root: Path, key: str, task: dict[str, Any], state: dict[str, Any]) -> None:
    dirty_list = ", ".join(_dirty_files(root))
    dirty_hint = f" ({dirty_list})" if dirty_list else ""
    reason = (
        "canonical-dirty: canonical is dirty; ag_verify refused before tests, probes, critic, and switch"
        f"{dirty_hint} [原因] 主仓存在未提交或未忽略的改动 "
        "[下一步] 请先清理主仓改动（恢复或 git stash），确保仅在 worktree 内施工后再调用 ag_verify"
    )
    porcelain = git(root, "status", "--porcelain", check=False)[:4000]
    evidence = {
        "refused": "canonical-dirty",
        "reason": reason,
        "canonical_dirty": True,
        "hazards": [str(item) for item in (state.get("hazards") or [])],
        "porcelain": porcelain,
    }
    task["verify"] = {
        "exit": 1,
        "stdout": "",
        "stderr": reason,
        "undeclared": not bool(state.get("test_argv")),
        "refused": "canonical-dirty",
        "evidence": {"canonical_dirty": evidence},
    }
    task["verified_tree"] = ""
    save_task(key, task)
    usage_note(root, "ship", 8, "block", "verify canonical dirty")
    append_task_step(
        root,
        str(task.get("id") or ""),
        "verify-refused",
        reason=reason,
        refused="canonical-dirty",
        porcelain=porcelain,
    )
    raise ChainBroken(reason)


def verify(root: Path) -> dict[str, Any]:
    state = status(root)
    key = str(state["key"])
    task = load_task(key)
    if not task:
        raise ChainBroken(
            "no open task; ag_start first "
            "[原因] 当前没有进行中的票据任务 "
            "[下一步] 请先编写 <AG_HOME>/projects/<key>/ticket.md 并调用 ag_start"
        )
    if not bool(task.get("intent_map_confirmed")):
        reason = (
            "intent-map-unconfirmed: ag_verify refused; user must confirm the anchor map first "
            "[原因] 尚未由用户确认意图锚点预览（工作树仍处于冻结态） "
            "[下一步] 展示 anchor_preview 全文，由用户亲自执行 confirm-map 后再执行 ag_verify；AI 不得代调"
        )
        task["verify"] = {"exit": 1, "stderr": reason, "refused": "intent-map-unconfirmed"}
        task["verified_tree"] = ""
        save_task(key, task)
        usage_note(root, "ship", 8, "block", "verify intent map unconfirmed")
        append_task_step(root, str(task.get("id") or ""), "verify-refused", reason=reason, refused="intent-map-unconfirmed")
        raise ChainBroken(reason)
    worktree = Path(str(task.get("worktree") or ""))
    from .authorization import require_construction

    require_construction(Path(state["root"]), task)
    if not worktree.is_dir():
        raise ChainBroken(
            f"worktree missing: {worktree} "
            "[原因] 隔离工作树目录不存在 "
            "[下一步] 请调用 ag_abandon 清理失效任务后重新调用 ag_start"
        )
    if state.get("canonical_dirty"):
        _refuse_dirty_verify(Path(state["root"]), key, task, state)
    task_id = str(task.get("id") or "")
    enrolled = Path(state["root"])
    ensure_start_step(enrolled, task_id, task.get("portrait"), worktree)
    from .checks import run as run_checks, selection

    chosen_checks = selection(worktree, [str(x) for x in (state.get("test_argv") or [])])
    test_argv = chosen_checks["commands"]
    candidate_before = tree_digest(worktree)
    untracked = [
        ln.strip()
        for ln in git(worktree, "ls-files", "-o", "--exclude-standard", check=False).splitlines()
        if ln.strip()
    ]
    timings: dict[str, float] = {}
    t0 = time.perf_counter()
    t_tests = time.perf_counter()
    record = {**run_checks(worktree, chosen_checks), "untracked": untracked[:50], "task_id": task_id, "candidate": candidate_before}
    timings["tests_s"] = round(time.perf_counter() - t_tests, 3)
    append_task_step(enrolled, task_id, "verify-tests", seconds=timings["tests_s"])
    paths = _ticket_paths(worktree, str(task.get("source_head") or ""))
    probe_results: list[Any] = []
    if paths:
        from .probe import run as probe_run

        probe_out = probe_run(Path(state["root"]), paths=paths, awaken=True, tree=worktree)
        raw = probe_out.get("results") if isinstance(probe_out, dict) else []
        probe_results = [row for row in raw if isinstance(row, dict)] if isinstance(raw, list) else []
    record["evidence"] = {
        "tests": {
            "declared": not bool(record.get("undeclared")),
            "exit": record.get("exit"),
            "stdout_tail": str(record.get("stdout") or "")[-1200:],
            "stderr_tail": str(record.get("stderr") or "")[-1200:],
        },
        "probes": [
            {
                "id": row.get("id"),
                "verdict": row.get("verdict"),
                "exit": row.get("exit"),
                "tail": str(row.get("tail") or "")[-600:],
            }
            for row in probe_results
            if isinstance(row, dict)
        ],
    }
    record["probes"] = probe_results
    record["probe_red"] = [
        str(row.get("id") or "") for row in probe_results if row.get("verdict") == "red" and row.get("id")
    ]
    from .probe import missing_fragments

    record["missing"] = missing_fragments(Path(state["root"]), list(record["probe_red"]))
    from .worker import artifacts_dir

    worker_root = artifacts_dir(worktree) / "workers"
    worker_dirs = [item for item in worker_root.iterdir() if item.is_dir()] if worker_root.is_dir() else []
    missing_worker_results: list[str] = []
    for worker_path in worker_dirs:
        if not (worker_path / "task.json").is_file():
            continue
        if not (worker_path / "result.json").is_file():
            missing_worker_results.append(worker_path.name)
    if missing_worker_results:
        record["exit"] = 1
        record["stderr"] = (
            (record.get("stderr") or "")
            + ("\n" if record.get("stderr") else "")
            + "missing worker results: " + ", ".join(missing_worker_results)
        )
        record["missing_worker_results"] = missing_worker_results
    record["evidence"]["workers"] = {
        "count": len(worker_dirs),
        "missing_results": missing_worker_results,
    }
    timings["probes_s"] = round(time.perf_counter() - t_tests - timings["tests_s"], 3)
    append_task_step(enrolled, task_id, "verify-probes", probe_red=list(record["probe_red"]), seconds=timings["probes_s"])
    portrait = str(task.get("portrait") or "").strip()
    anchor_exam = _anchor_exam(task)
    if anchor_exam:
        portrait = f"{portrait}\n\n{anchor_exam}" if portrait else anchor_exam
    probe_red = list(record["probe_red"])
    sealed_redlines = [str(item) for item in (task.get("redlines") or [])]
    from .switch import attach_verify as attach_switch

    t_switch = time.perf_counter()
    switch = attach_switch(
        enrolled,
        worktree=worktree,
        portrait=portrait,
        task_id=task_id,
        probe_red=probe_red,
        critic=None,
        tests_failed=bool(test_argv) and int(record.get("exit") or 0) != 0,
        verification={"task_id": task_id, "candidate": candidate_before, "check_selection": chosen_checks, **record["evidence"]},
        redlines=sealed_redlines,
        source_head=str(task.get("source_head") or ""),
    )
    timings["switch_s"] = round(time.perf_counter() - t_switch, 3)
    timings["critic_s"] = 0.0
    planted = list(switch.get("probes_planted") or [])
    if not planted and str(switch.get("outcome") or "") == "rejected":
        from .probe import plant_from_reject
        from .seat import report_path as seat_report_path

        try:
            sw_blob = json.loads(seat_report_path("switch", enrolled).read_text(encoding="utf-8"))
            planted = list(plant_from_reject(
                enrolled, items=sw_blob.get("items"), tree=worktree,
                source_head=str(task.get("source_head") or ""), task_id=task_id,
            ) or [])
        except Exception:
            planted = []
    critic = dict(switch)
    critic["merged_into"] = "switch"
    if planted:
        record["probes_planted"] = planted
    record["critic"] = critic
    record["evidence"]["critic"] = {
        "outcome": critic.get("outcome"),
        "report_id": critic.get("report_id"),
        "store": critic.get("store"),
        "model": critic.get("model"),
        "merged_into": "switch",
    }
    record["switch"] = switch
    record["evidence"]["switch"] = {
        "outcome": switch.get("outcome"),
        "report_id": switch.get("report_id"),
        "store": switch.get("store"),
        "model": switch.get("model"),
        "redlines": list(switch.get("redlines") or sealed_redlines),
    }
    append_task_step(enrolled, task_id, "verify-switch", report_id=str(switch.get("report_id") or ""), outcome=str(switch.get("outcome") or ""), seconds=timings["switch_s"])
    timings["total_s"] = round(time.perf_counter() - t0, 3)
    record["timings"] = timings
    record["evidence"]["anchor_map_path"] = str(task.get("anchor_map_path") or "")
    record["evidence"]["anchor_preview_path"] = str(task.get("anchor_preview_path") or "")
    record["evidence"]["anchor_preview"] = str(task.get("anchor_preview") or "")
    record["evidence"]["current_anchor"] = task.get("current_anchor") or ""
    record["evidence"]["timings"] = dict(timings)
    digest = tree_digest(worktree)
    if digest != candidate_before or selection(worktree, [str(x) for x in (state.get("test_argv") or [])])["sha256"] != chosen_checks["sha256"]:
        record["exit"] = 1
        record["stderr"] += "\ncandidate-changed: code or checks changed during verification"
    task["verify"] = record
    task["verified_tree"] = digest if record["exit"] == 0 and not record["probe_red"] and not _switch_block_message(record) else ""
    task["check_argv"] = test_argv
    record["evidence"]["verified_tree"] = task["verified_tree"]
    save_task(key, task)
    from .delivery import task_facts

    append_task_step(enrolled, task_id, "verify-result", verify=record, task=task_facts(task))
    if record.get("undeclared"):
        usage_note(root, "ship", 1, "help", "verify without tests")
    elif record["exit"] == 0:
        usage_note(root, "ship", 6, "help", "tests passed")
        usage_note(root, "ship", 7, "help", "pinned")
    else:
        usage_note(root, "ship", 6, "block", f"exit {record['exit']}")
    out = status(root)
    out["verify"] = record
    out["verified_tree"] = task["verified_tree"]
    out["probes"] = probe_results
    out["probe_red"] = list(record["probe_red"])
    out["missing"] = list(record["missing"])
    out["critic"] = critic
    out["switch"] = switch
    out["switch_report_id"] = str(switch.get("report_id") or "")
    out["probes_planted"] = list(record.get("probes_planted") or [])
    out["timings"] = dict(record.get("timings") or {})
    out["evidence"] = {
        "tests": {
            "declared": not bool(record.get("undeclared")),
            "exit": record.get("exit"),
            "stdout_tail": str(record.get("stdout") or "")[-1200:],
            "stderr_tail": str(record.get("stderr") or "")[-1200:],
        },
        "probes": [
            {
                "id": row.get("id"),
                "verdict": row.get("verdict"),
                "exit": row.get("exit"),
                "tail": str(row.get("tail") or "")[-600:],
            }
            for row in probe_results
            if isinstance(row, dict)
        ],
        "critic": {
            "outcome": critic.get("outcome"),
            "report_id": critic.get("report_id"),
            "store": critic.get("store"),
            "model": critic.get("model"),
            "merged_into": "switch",
        },
        "switch": {
            "outcome": switch.get("outcome"),
            "report_id": switch.get("report_id"),
            "store": switch.get("store"),
            "model": switch.get("model"),
            "redlines": list(switch.get("redlines") or sealed_redlines),
        },
        "anchor_map_path": str((task or {}).get("anchor_map_path") or ""),
        "anchor_preview_path": str((task or {}).get("anchor_preview_path") or ""),
        "anchor_preview": str((task or {}).get("anchor_preview") or ""),
        "current_anchor": str((task or {}).get("current_anchor") or ""),
        "workers": dict((task.get("verify") or {}).get("evidence", {}).get("workers", {})),
        "verified_tree": task.get("verified_tree") or "",
        "timings": dict(record.get("timings") or {}),
    }
    try:
        from .lift import run as lift_run

        out["lift"] = lift_run(root)
    except Exception:
        pass
    return out


def confirm_map(root: Path, *, by: str = "") -> dict[str, Any]:
    started = time.perf_counter()
    stages = []
    def stage(name: str) -> None:
        elapsed = round(time.perf_counter() - started, 3)
        stages.append({"stage": name, "seconds": elapsed})
        print(f"ag confirm-map: {name} ({elapsed:.3f}s)", file=sys.stderr, flush=True)
    stage("checking-authority")
    root = real_root(root)
    item = lookup_project(root)
    if not item:
        raise ChainBroken(f"not-enrolled: {root}")
    key = str(item.get("key") or project_key(root))
    task = load_task(key)
    if not task:
        raise ChainBroken(
            "no open task; ag_start first "
            "[原因] 当前没有进行中的票据任务 "
            "[下一步] 请先编写 <AG_HOME>/projects/<key>/ticket.md 并调用 ag_start"
        )
    from .authorization import validate_ticket
    from .delivery import build_delivery_snapshot
    from .freeze import _tracked_files, assert_frozen

    identity = validate_ticket(root, task)
    if not _hook_ok(root, key):
        raise ChainBroken("hook-removed: enroll to repair the canonical gate")
    if _dirty(root):
        raise ChainBroken("canonical-dirty: clean canonical before confirmation")
    if git(root, "rev-parse", "HEAD") != task.get("source_head") or git(root, "symbolic-ref", "--short", "HEAD") != task.get("branch"):
        raise ChainBroken("intent-identity-changed: canonical candidate or branch changed")
    worktree = Path(str(task.get("worktree") or ""))
    expected = (ag_home() / "worktrees" / key / str(task["id"])).resolve()
    if worktree.resolve() != expected or not worktree.is_dir():
        raise ChainBroken("intent-identity-changed: worktree identity changed or missing")
    registered = git(root, "worktree", "list", "--porcelain")
    if not any(block.splitlines()[0] == "worktree " + _posix(worktree.resolve()) and f"branch refs/heads/ag/{task['id']}" in block.splitlines() and (task.get("intent_map_confirmed") or f"HEAD {task['source_head']}" in block.splitlines()) for block in registered.strip().split("\n\n")):
        raise ChainBroken("intent-identity-changed: worktree registration changed")
    canonical_files = _tracked_files(root)
    try:
        assert_frozen(canonical_files)
    except OSError as exc:
        raise ChainBroken(f"canonical-freeze-missing: {exc}") from exc
    worktree_files = _tracked_files(worktree)
    if not task.get("intent_map_confirmed"):
        task["intent_map_confirmed_at"] = datetime.now(timezone.utc).isoformat()
        task["intent_map_confirmed_by"] = str(by or "user-cli")
        task["intent_map_confirmed"] = True
        task["authorization_identity"] = identity
        task["intent_identity"] = identity
        task["worktree_ready"] = False
        save_task(key, task)
        append_task_step(root, task["id"], "intent-map-confirmed", by=task["intent_map_confirmed_by"], intent_identity=identity)
    stage("approval-recorded")
    try:
        stage("thawing-worktree")
        thaw_worktree(worktree, files=worktree_files)
        append_task_step(root, task["id"], "worktree-ready", intent_identity=identity)
        task["worktree_ready"] = True
        task.pop("thaw_error", None)
        save_task(key, task)
    except (OSError, ChainBroken) as exc:
        task["worktree_ready"] = False
        task["thaw_error"] = str(exc)
        record_error = ""
        try:
            save_task(key, task)
            append_task_step(root, task["id"], "thaw-failed", error=str(exc))
        except (OSError, ChainBroken) as failure:
            record_error = f"; failure record could not be saved: {failure}"
        stage("thaw-failed")
        raise ChainBroken(f"thaw-failed: approval retained; retry confirm-map after repairing permissions: {exc}{record_error}") from exc
    stage("ready")
    return {"schema": "ag.confirm-map.v2", "root": str(root), "key": key, "intent_map_confirmed": True, "readiness": "ready", "worktree": str(worktree), "task": task, "delivery": build_delivery_snapshot(root, task["id"]), "stages": stages}


def _cleanup(root: Path, task: dict[str, Any]) -> None:
    worktree = Path(str(task.get("worktree") or ""))
    task_id = str(task.get("id") or "")
    container = (ag_home() / "worktrees" / project_key(root)).resolve()
    expected = container / task_id
    if not task_id or worktree.resolve() != expected or not worktree.resolve().is_relative_to(container):
        raise ChainBroken("cleanup-pending: worktree path is outside this task's managed container")
    side = container / f"{task_id}.artifacts"
    if side.resolve().parent != container:
        raise ChainBroken("cleanup-pending: artifact path escapes the managed container")
    registration = git(root, "worktree", "list", "--porcelain")
    registered = "worktree " + _posix(worktree.resolve()) in registration.splitlines()
    if worktree.is_dir() and (worktree / ".git").exists():
        thaw_worktree(worktree)
    if registered:
        git(root, "worktree", "remove", "--force", str(worktree))
    elif worktree.is_dir():
        shutil.rmtree(worktree)
    if worktree.exists() or "worktree " + _posix(worktree.resolve()) in git(root, "worktree", "list", "--porcelain").splitlines():
        raise ChainBroken("cleanup-pending: worktree removal incomplete")
    if side.is_dir():
        shutil.rmtree(side)
    reference = f"refs/heads/ag/{task_id}"
    if git_run(root, "show-ref", "--verify", "--quiet", reference).returncode == 0:
        git(root, "branch", "-D", f"ag/{task_id}")


def _close_task(root: Path, key: str, task: dict[str, Any], *, process: str, product: str, head: str = "") -> dict[str, Any]:
    from .delivery import build_delivery_snapshot, task_facts
    from .knowledge import archive_session
    from .ticket_doc import write_scene

    task["process"] = process
    task["close_product"] = product
    if head:
        task["merged_head"] = head
    save_task(key, task)
    if not task.get("close_recorded"):
        worktree = Path(str(task.get("worktree") or ""))
        touched = _ticket_paths(worktree, str(task.get("source_head") or "")) if worktree.is_dir() else []
        verify_blob = task.get("verify") if isinstance(task.get("verify"), dict) else None
        try:
            write_scene(root, task, process=process, product=product)
            archive_session(root, task, verify=verify_blob, touched=touched, check_exit=(verify_blob or {}).get("exit"), process=process, product=product)
            append_task_step(root, task["id"], "finish" if process == "completed" else "abandon", head=head, product=product, task=task_facts(task), switch_report_id=_switch_report_id(verify_blob))
            task["close_recorded"] = True
            task.pop("archive_error", None)
            save_task(key, task)
        except Exception as exc:
            task["archive_error"] = str(exc)
            save_task(key, task)
            raise ChainBroken(f"history-close-pending: task and worktree retained; retry {process}: {exc}") from exc
    try:
        _cleanup(root, task)
    except Exception as exc:
        task["cleanup_error"] = str(exc)
        save_task(key, task)
        append_task_step(root, task["id"], "cleanup-pending", error=str(exc), task=task_facts(task))
        raise ChainBroken(f"cleanup-pending: task retained; retry finish/abandon: {exc}") from exc
    task.pop("cleanup_error", None)
    append_task_step(root, task["id"], "cleanup-complete", task=task_facts(task))
    blob = load_managed()
    for row in blob["projects"]:
        if isinstance(row, dict) and str(row.get("key") or "") == key:
            row["last_product"] = product
            row["last_process"] = process
            break
    save_managed(blob)
    save_task(key, None)
    return build_delivery_snapshot(root, task["id"])


def finish(root: Path) -> dict[str, Any]:
    state = status(root)
    root = Path(state["root"])
    key = str(state["key"])
    task = load_task(key)
    if not task:
        raise ChainBroken(
            "no open task "
            "[原因] 当前没有进行中的票据任务 "
            "[下一步] 请先调用 ag_start"
        )
    if task.get("process") == "completed" and task.get("merged_head"):
        if git(root, "rev-parse", "HEAD") != task["merged_head"]:
            raise ChainBroken("cleanup-pending: canonical moved since merge; inspect before retry")
        thaw_canonical(root)
        delivery = _close_task(root, key, task, process="completed", product=task.get("close_product") or "undeclared", head=task["merged_head"])
        return {"schema": "ag.finish.v1", "root": str(root), "head": task["merged_head"], "process": "completed", "product": task.get("close_product"), "delivery": delivery, "recovered": True}

    def _no(reason: str, lane: int = 6, detail: str = "") -> None:
        usage_note(root, "ship", lane, "block", detail or reason)
        append_task_step(root, str(task.get("id") or ""), "finish-refused", reason=reason)
        raise ChainBroken(reason)

    if not bool(task.get("intent_map_confirmed")):
        _no(
            "intent map is not confirmed; user approval is required "
            "[原因] 用户尚未确认意图锚点 "
            "[下一步] 展示 anchor_preview，由用户亲自执行 confirm-map，再 ag_verify -> ag_finish；AI 不得代调",
            8,
            "finish intent map unconfirmed",
        )
    from .authorization import validate_ticket

    validate_ticket(root, task)
    if not state["hook_ok"]:
        _no(
            "hook-removed: will not deliver "
            "[原因] Git 门禁钩子缺失 "
            "[下一步] 请调用 ag_enroll 修复钩子并重新执行 ag_verify 后再调用 ag_finish",
            8,
            "finish hook-removed",
        )
    if state["canonical_dirty"]:
        _no(
            "canonical is dirty; will not deliver "
            "[原因] 主仓存在未提交改动 "
            "[下一步] 请清理主仓改动并重新执行 ag_verify 后再调用 ag_finish",
            8,
            "finish canonical dirty",
        )
    current = git(root, "rev-parse", "--abbrev-ref", "HEAD")
    if current != str(task.get("branch") or ""):
        _no(
            f"canonical is on {current}, task started on {task.get('branch')} "
            "[原因] 主仓当前分支与开票时的分支不一致 "
            f"[下一步] 请将主仓切换回 {task.get('branch')} 分支后再调用 ag_finish"
        )
    worktree = Path(str(task.get("worktree") or ""))
    if not worktree.is_dir():
        _no(
            "worktree missing "
            "[原因] 隔离工作树目录缺失 "
            "[下一步] 请调用 ag_abandon 清理任务后重新开票"
        )
    if not task.get("verified_tree"):
        _no(
            "not verified "
            "[原因] 当前工作树尚未通过 ag_verify 验货 "
            "[下一步] 请先调用 ag_verify 并确保验证通过后再调用 ag_finish"
        )
    digest = tree_digest(worktree)
    if digest != task.get("verified_tree"):
        _no(
            "tree digest mismatch; run ag_verify again "
            "[原因] ag_verify 之后工作树内容发生了变动 "
            "[下一步] 请重新调用 ag_verify 锁定最新工作树摘要后再调用 ag_finish",
            7,
            "mismatch",
        )
    verify_blob = task.get("verify") if isinstance(task.get("verify"), dict) else None
    if verify_blob and verify_blob.get("task_id", task["id"]) != task["id"]:
        _no("wrong-task: verification receipt belongs to another ticket")
    if verify_blob and verify_blob.get("check_selection"):
        from .checks import selection

        current_checks = selection(worktree, [str(argument) for argument in state.get("test_argv") or []])
        if current_checks["sha256"] != verify_blob["check_selection"].get("sha256"):
            _no("check-digest-mismatch: current ticket checks changed; run ag_verify again")
    switch_receipt = (verify_blob or {}).get("switch") or {}
    if switch_receipt.get("configured"):
        from .store import list_llm_events

        originals = list_llm_events(root, "switch_event", 0, task_id=task["id"], report_id=str(switch_receipt.get("report_id") or ""), candidate=digest)
        if len(originals) != 1 or originals[0].get("outcome") != switch_receipt.get("outcome") or (verify_blob or {}).get("candidate") != digest:
            _no("missing-evidence: switch receipt is not bound to this task and candidate; run ag_verify again")
    red = _probe_red_ids(verify_blob)
    if red:
        _no(
            "probe red: " + ", ".join(red) + "; will not deliver "
            "[原因] 探针检查未通过 "
            "[下一步] 请修复红灯探针指出的问题并重新调用 ag_verify",
            6,
            "probe " + ",".join(red),
        )
    switch_block = _switch_block_message(verify_blob)
    if switch_block:
        if _is_self_governance(root):
            task_id = str(task.get("id") or "")
            if task.get("self_approved"):
                task["self_governed_approved"] = {
                    "outcome": str((verify_blob.get("switch") or {}).get("outcome") or ""),
                    "report_id": _switch_report_id(verify_blob),
                    "reason": str((verify_blob.get("switch") or {}).get("reason") or ""),
                    "approved": True,
                }
                save_task(key, task)
                append_task_step(root, task_id, "self-governed-approved")
            else:
                switch_rec = verify_blob.get("switch") or {}
                task["self_governance_pending"] = {
                    "outcome": str(switch_rec.get("outcome") or ""),
                    "report_id": _switch_report_id(verify_blob),
                    "reason": str(switch_rec.get("reason") or ""),
                }
                save_task(key, task)
                usage_note(root, "ship", 6, "block", "self-governance pending approval")
                append_task_step(root, task_id, "self-governance-pending")
                raise ChainBroken(
                    "self-governance pending approval "
                    "[原因] 本票改动触及 ag 自身（src/ag/**），switch 拒单后需人工放行 "
                    f"[下一步] 请核对后运行 python -m ag approve-self {root} {task_id} 再放行 ag_finish"
                )
        else:
            _no(switch_block)
    thaw_canonical(root)
    try:
        return _finish_after_thaw(root, key, state, task, worktree)
    except Exception:
        if load_task(key):
            freeze_canonical(root)
        raise


def _finish_after_thaw(
    root: Path,
    key: str,
    state: dict[str, Any],
    task: dict[str, Any],
    worktree: Path,
) -> dict[str, Any]:
    git(worktree, "add", "-A")
    if git(worktree, "status", "--porcelain", check=False):
        first_line = (str(task.get("portrait") or "").strip().splitlines() or [""])[0][:70]
        title = first_line or f"ag {task.get('id')}"
        token_path = _deliver_token_path(key)
        token = uuid.uuid4().hex
        token_path.parent.mkdir(parents=True, exist_ok=True)
        token_path.write_text(token, encoding="utf-8")
        try:
            deliver = os.environ.copy()
            deliver["AG_DELIVER"] = "1"
            deliver["AG_DELIVER_TOKEN"] = token
            git(worktree, "commit", "-m", title, env=deliver)
            usage_note(root, "ship", 4, "help", "AG_DELIVER commit")
        finally:
            try:
                token_path.unlink()
            except OSError:
                pass
    try:
        git(root, "merge", "--ff-only", f"ag/{task.get('id')}")
    except ChainBroken:
        usage_note(root, "ship", 5, "block", "merge")
        append_task_step(root, str(task.get("id") or ""), "finish-refused", reason="merge")
        raise
    usage_note(root, "ship", 5, "help", "merged")
    usage_note(root, "ship", 7, "help", "matched")
    portrait = str(task.get("portrait") or "")
    product = _product([str(x) for x in (state.get("test_argv") or [])], task.get("verify") if isinstance(task.get("verify"), dict) else None)
    from .ticket_doc import write_scene

    write_scene(root, task, process="completed", product=product)
    head = git(root, "rev-parse", "HEAD")
    vblob = task.get("verify") if isinstance(task.get("verify"), dict) else None
    anchors = [dict(item) for item in (task.get("anchors") or []) if isinstance(item, dict)]
    current_anchor = str(task.get("current_anchor") or (anchors[0].get("id") if anchors else ""))
    anchor_progress = {
        "anchors": anchors,
        "anchor_map_path": str(task.get("anchor_map_path") or ""),
        "anchor_preview_path": str(task.get("anchor_preview_path") or ""),
        "anchor_preview": str(task.get("anchor_preview") or ""),
        "current_anchor": current_anchor,
        "reminder": "Before accepting delivery, re-read the intent map and compare each anchor with the final result; soft anchors are not auto-completion states.",
    }
    from .knowledge import append_redlines, distill
    from .state_git import commit_state

    delivery = _close_task(root, key, task, process="completed", product=product, head=head)
    try:
        try:
            append_redlines(root, task)
        except Exception:
            pass
        distill(root)
        commit_state(root, f"finish {task.get('id')}: product={product}")
    except Exception as exc:
        usage_note(root, "see", 14, "help", f"knowledge archive skipped: {exc.__class__.__name__}")
    if product == "undeclared":
        usage_note(root, "ship", 1, "help", "finish undeclared")
    elif product == "passed":
        usage_note(root, "ship", 6, "help", "finish passed")
    return {
        "schema": "ag.finish.v1",
        "root": str(root),
        "process": "completed",
        "product": product,
        "reminder": "process complete is not product passed",
        "portrait": portrait,
        "anchor_progress": anchor_progress,
        "critic_report_id": _critic_report_id(task.get("verify") if isinstance(task.get("verify"), dict) else None),
        "switch_report_id": _switch_report_id(task.get("verify") if isinstance(task.get("verify"), dict) else None),
        "head": head,
        "hazards": [],
        "delivery": delivery,
    }


def approve_self(root: Path, task_id: str = "") -> dict[str, Any]:
    """Record explicit human approval for a self-governance ticket whose switch rejected it.

    Only valid when the open task touches ag itself (canonical root has src/ag/__init__.py)
    and finish has parked it in the self_governance_pending state. Anything else refuses.
    """
    state = status(root)
    root = Path(state["root"])
    key = str(state["key"])
    task = load_task(key)
    if not task:
        raise ChainBroken(
            "no open task "
            "[原因] 当前没有进行中的票据任务 "
            "[下一步] 请先调用 ag_start"
        )
    if not _is_self_governance(root):
        raise ChainBroken(
            "not a self-governance repo "
            "[原因] 目标仓根不存在 src/ag/__init__.py，本票不是改 ag 自己 "
            "[下一步] approve-self 仅用于改 ag 自身的票"
        )
    tid = str(task.get("id") or "")
    if task_id and task_id != tid:
        raise ChainBroken(
            f"task id mismatch: given {task_id}, open task is {tid} "
            "[原因] 指定票号与当前开放票不一致 "
            f"[下一步] 请改用 python -m ag approve-self {root} {tid}"
        )
    pending = task.get("self_governance_pending")
    if not isinstance(pending, dict):
        raise ChainBroken(
            "no self-governance pending approval "
            "[原因] 本票未处于 switch 拒单后的待批准态（或 switch 未拒/已通过） "
            "[下一步] 请先跑 ag_verify 再 ag_finish，待其停在待批准提示后再批准"
        )
    task["self_approved"] = {
        "by": "approve-self",
        "task_id": tid,
        "report_id": str(pending.get("report_id") or ""),
        "outcome": str(pending.get("outcome") or ""),
        "ts": datetime.now(timezone.utc).isoformat(),
    }
    save_task(key, task)
    usage_note(root, "ship", 6, "help", "self-governance approved")
    append_task_step(root, tid, "self-governance-approved")
    return status(root)


def abandon(root: Path) -> dict[str, Any]:
    state = status(root)
    root = Path(state["root"])
    key = str(state["key"])
    task = load_task(key)
    thaw_canonical(root)
    if not task:
        return status(root)
    if task.get("process") == "completed":
        raise ChainBroken("cleanup-pending: already merged; retry finish to complete cleanup")
    try:
        from .probe import drop_newborn_for_task

        drop_newborn_for_task(root, task_id=str(task.get("id") or ""), by="ag-abandon")
        delivery = _close_task(root, key, task, process="abandoned", product="undeclared")
    finally:
        thaw_canonical(root)
    return {**status(root), "delivery": delivery}


def unenroll(root: Path) -> dict[str, Any]:
    state = status(root)
    root = Path(state["root"])
    key = str(state["key"])
    if load_task(key):
        raise ChainBroken("abandon the open task before unenroll")
    item = lookup_project(root) or {}
    previous = str(
        item.get("previous_hooks_path")
        or git(root, "config", "--local", "--get", "ag.previousHooksPath", check=False)
        or PREV_UNSET
    )
    _restore_git_gate(root, previous)
    _drop_project(key)
    shutil.rmtree(_hooks_dir(key), ignore_errors=True)
    usage_note(root, "ship", 11, "help", "restored hooksPath")
    return {
        "schema": "ag.unenroll.v1",
        "root": str(root),
        "unenrolled": True,
        "restored_hooksPath": None if previous == PREV_UNSET else previous,
    }
