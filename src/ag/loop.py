def _deliver_token_ok(root: Path) -> bool:
    key = git(root, "config", "--local", "--get", "ag.key", check=False) or project_key(root)
    try:
        expected = _deliver_token_path(key).read_text(encoding="utf-8").strip()
    except OSError:
        return False
    got = os.environ.get("AG_DELIVER_TOKEN") or ""
    if not expected or len(got) != len(expected):
        return False
    return hmac.compare_digest(got, expected)


# 本地忽略项：本票一次性自检脚本目录。ag 不往通用名数据目录里写任何东西，那条也就没有存在的必要。
LOCAL_EXCLUDE_ENTRIES: tuple[str, ...] = (".ag-check/",)


def ensure_local_excludes(root: Path) -> dict[str, Any]:
    common_raw = git(root, "rev-parse", "--git-common-dir", check=False)
    if not common_raw:
        return {"exclude_path": "", "entries": [], "exclude_ready": False}
    git_common = _resolve_git_path(root, common_raw)
    exclude_path = git_common / "info" / "exclude"
    try:
        existing_text = exclude_path.read_text(encoding="utf-8", errors="replace") if exclude_path.is_file() else ""
    except OSError:
        existing_text = ""
    existing_norms = {
        line.strip().lstrip("/").rstrip("/")
        for line in existing_text.splitlines()
        if line.strip() and not line.strip().startswith("#")
    }
    missing = [
        entry
        for entry in LOCAL_EXCLUDE_ENTRIES
        if entry.strip().lstrip("/").rstrip("/") not in existing_norms
    ]
    if missing or not exclude_path.is_file():
        try:
            exclude_path.parent.mkdir(parents=True, exist_ok=True)
            prefix = existing_text
            if prefix and not prefix.endswith("\n"):
                prefix += "\n"
            addition = "".join(f"{entry}\n" for entry in missing)
            exclude_path.write_text(prefix + addition, encoding="utf-8")
        except OSError:
            return {"exclude_path": str(exclude_path), "entries": list(LOCAL_EXCLUDE_ENTRIES), "exclude_ready": False}
    return {
        "exclude_path": str(exclude_path),
        "entries": list(LOCAL_EXCLUDE_ENTRIES),
        "exclude_ready": True,
    }


def _dirty_files(root: Path, limit: int = 8) -> list[str]:
    files: list[str] = []
    raw_out = git_run(root, "status", "--porcelain").stdout or ""
    for line in raw_out.splitlines():
        body = line[3:] if len(line) > 3 and line[2] == " " else (line.split(None, 1)[1] if len(line.split(None, 1)) > 1 else "")
        path = body.replace("\\", "/").strip().strip('"')
        if not path or path == ".ag" or path.startswith(".ag/"):
            continue
        if path not in files:
            files.append(path)
        if len(files) >= limit:
            break
    return files


def _dirty(root: Path) -> bool:
    return bool(_dirty_files(root, limit=1))


def _ticket_paths(worktree: Path, source_head: str) -> list[str]:
    names: list[str] = []
    if source_head:
        for line in git(worktree, "diff", "--name-only", source_head, check=False).splitlines():
            rel = line.replace("\\", "/").strip().strip('"')
            if rel and rel not in names:
                names.append(rel)
    for line in git(worktree, "ls-files", "-o", "--exclude-standard", check=False).splitlines():
        rel = line.replace("\\", "/").strip().strip('"')
        if rel and rel not in names:
            names.append(rel)
    return names


def _probe_red_ids(verify: dict[str, Any] | None) -> list[str]:
    if not isinstance(verify, dict):
        return []
    listed = verify.get("probe_red")
    if isinstance(listed, list) and listed:
        return [str(item) for item in listed if str(item)]
    results = verify.get("probes")
    if not isinstance(results, list):
        return []
    return [
        str(row.get("id") or "")
        for row in results
        if isinstance(row, dict) and row.get("verdict") == "red" and row.get("id")
    ]


